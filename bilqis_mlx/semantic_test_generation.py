"""On-demand, type-dependency-aware generated test suites for Bilqis.

Explicit `--regenerate-tests=type:integer` atomically publishes a new set of
integer-derived suites. Nothing is generated by normal tests or training.
Historical frozen Grade A examination files are never opened for writing.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from .pedagogical_parity import build_plan
from .verification.generated_tests.contracts import (
    Family,
    FAMILIES,
    SCHEMA,
    ROOT,
    LEGACY,
    _json,
    _hash,
    _object_hash,
    select_families,
    _dependency_state,
)
from .verification.generated_tests.cases import (
    _case,
    _generated_cases,
    _suite,
)
from .verification.generated_tests.storage import (
    _read_release,
)
from .verification.generated_tests.publication import (
    status,
    regenerate,
)
from .verification.generated_tests.validation import (
    _validate_case,
    check_generated,
)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    choice=parser.add_mutually_exclusive_group(required=True)
    choice.add_argument("--regenerate-tests", metavar="SELECTOR")
    choice.add_argument("--plan-tests", metavar="SELECTOR")
    choice.add_argument("--check-tests", metavar="SELECTOR")
    parser.add_argument("--seed", type=int, default=20261015)
    parser.add_argument("--count", type=int, default=40)
    parser.add_argument("--output-dir", type=Path, default=ROOT)
    parser.add_argument("--legacy-root", type=Path, default=LEGACY)
    args=parser.parse_args(argv)
    parity=build_plan(args.legacy_root)
    if args.regenerate_tests:
        result=regenerate(parity,args.legacy_root,args.output_dir,
                          selector=args.regenerate_tests,seed=args.seed,count=args.count)
        print(json.dumps({"regenerated":select_families(args.regenerate_tests),
                          "release_sha256":result["release_sha256"],
                          "integer_max":result["integer_max"],
                          "output_dir":str(args.output_dir)},indent=2))
    elif args.plan_tests:
        print(json.dumps(status(parity,args.output_dir,selector=args.plan_tests),indent=2))
    else:
        check_generated(parity,args.legacy_root,args.output_dir,
                        selector=args.check_tests)
        print("SEMANTIC_GENERATED_TESTS_VALID_AND_CURRENT")


if __name__ == "__main__":
    main()
