"""On-demand, type-dependency-aware generated test suites for Bilqis.

Explicit `--regenerate-tests=type:integer` atomically publishes a new set of
integer-derived suites. Nothing is generated by normal tests or training.
Historical frozen Grade A examination files are never opened for writing.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import shutil
import tempfile

from .integer_curriculum import (IntegerScope, _partition,
                                 generate_integer_curriculum)
from .pedagogical_parity import _source_stack, build_plan


SCHEMA = "bilqis.semantic.generated-tests/v1"
ROOT = Path(__file__).resolve().parents[1] / "artifacts" / "semantic-tests"
LEGACY = Path(__file__).resolve().parents[1] / "vendor" / "legacy-v16"


@dataclass(frozen=True)
class Family:
    name: str
    input_types: tuple[str, ...]
    output_type: str
    laws: tuple[str, ...] = ()

    @property
    def dependencies(self) -> tuple[str, ...]:
        types = set(self.input_types) | {self.output_type}
        return tuple(sorted({"type:integer" if kind == "Number" else
                             "type:boolean" for kind in types} |
                            {"law:" + law for law in self.laws}))


# These are generative *laws/types*, not enumerations of examples or golds.
# The source graph and two agreeing oracles determine every sampled answer.
FAMILIES = (
    Family("integer.direct", ("Number", "Number"), "Number"),
    Family("integer.truth", ("Number", "Number"), "Boolean"),
    Family("integer.equivalence", ("Number", "Number"), "Boolean",
           ("equivalence",)),
    Family("integer.inverse_negation", ("Number", "Number", "Boolean"),
           "Boolean", ("negation",)),
    Family("boolean.constants", ("Boolean",), "Boolean"),
)


def _json(value) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":"),
                       ensure_ascii=False) + "\n").encode()


def _hash(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _object_hash(value) -> str:
    return _hash(_json(value))


def select_families(selector: str) -> tuple[str, ...]:
    if selector == "all":
        return tuple(f.name for f in FAMILIES)
    if selector.startswith("family:"):
        name = selector.removeprefix("family:")
        if name in {f.name for f in FAMILIES}:
            return (name,)
    if selector in {tag for f in FAMILIES for tag in f.dependencies}:
        return tuple(f.name for f in FAMILIES if selector in f.dependencies)
    raise ValueError("SEMANTIC_TEST_SELECTOR_UNSUPPORTED:" + selector)


def _dependency_state(family: Family, scope: IntegerScope, parity: dict) -> dict:
    result = {"source_sha256": parity["source_sha256"],
              "graph_sha256": parity["graph_sha256"]}
    if "type:integer" in family.dependencies:
        result["type:integer"] = scope.maximum
    return result


def _case(source_id, partition, law, expected, **details):
    if partition == "train":
        raise ValueError("SEMANTIC_TEST_LEAKED_TRAINING_SOURCE")
    name = "sealed_proposed" if partition == "sealed" else partition
    return {"id": _object_hash([law, source_id, details]),
            "source_id": source_id, "partition": name,
            "law": law, "expected": expected, **details}


def _generated_cases(family: Family, sampled: dict, arithmetic,
                     source_graph: dict) -> list[dict]:
    cases = []
    if family.name == "boolean.constants":
        for value in (False, True):
            cases.append({"id": _object_hash(["Boolean", value]),
                          "source_id": _object_hash(["Boolean", value]),
                          "partition": "development", "law": "boolean_constant",
                          "expected": value, "type": "Boolean"})
        return cases
    not_node = next((node for node in source_graph["nodes"]
                     if node["id"] == "cogal.operator.NOT"), None)
    if (family.name == "integer.inverse_negation" and
            (not_node is None or not_node["signature"] != "Boolean->Boolean" or
             not_node["truth_signature"] != [False, True])):
        raise ValueError("SEMANTIC_TEST_NEGATION_TYPE_OR_TRUTH_TABLE_DRIFT")
    for source in sampled["rows"]:
        if source["partition"] == "train":
            continue
        ident = source["source_id"]
        split = source["partition"]
        direct, positive, negative = source["views"]
        value = source["value"]
        if family.name == "integer.direct":
            cases.append(_case(ident, split, "typed_direct_number", value,
                               record=direct["record"],
                               answer_kind=direct["answer_kind"],
                               native_output=direct["native_output"]))
        elif family.name == "integer.truth":
            for row in (positive, negative):
                cases.append(_case(ident, split, "typed_equality_truth",
                                   row["gold"] == "TRUE", record=row["record"],
                                   answer_kind="evidence"))
        elif family.name == "integer.equivalence":
            for row in (positive, negative):
                expression = row["record"]["expression"]
                swapped = arithmetic.operation("EQ", *reversed(expression["args"]))
                arithmetic.verify(swapped)
                cases.append(_case(ident, split, "equality_symmetric",
                                   row["gold"] == "TRUE",
                                   record=row["record"],
                                   comparison={"task":arithmetic.VERSION,
                                               "expression":swapped}))
        elif family.name == "integer.inverse_negation":
            for row in (positive, negative):
                original = row["gold"] == "TRUE"
                cases.append(_case(ident, split, "boolean_double_negation",
                                   original, record=row["record"],
                                   negated=not original,
                                   double_negated=not(not original),
                                   neural_codec_admitted=False))
        else:
            raise ValueError("SEMANTIC_TEST_MISSING_GENERATOR:" + family.name)
    if not cases:
        raise ValueError("SEMANTIC_TEST_NO_INDEPENDENT_EVALUATION_SOURCES:" + family.name)
    return cases


def _suite(family: Family, sampled, arithmetic, graph, scope, parity,
           seed: int, count: int):
    return {"schema": SCHEMA, "family": family.name,
            "dependencies": list(family.dependencies),
            "dependency_state": _dependency_state(family, scope, parity),
            "seed": seed, "sample_count": count,
            "status": "PROPOSED_GENERATED_TESTS_NOT_GRADE_QUALIFICATION",
            "cases": _generated_cases(family, sampled, arithmetic, graph)}


def _read_release(folder: Path):
    pointer = folder / "current.json"
    if not pointer.exists():
        return None, {}
    if pointer.is_symlink():
        raise ValueError("SEMANTIC_TEST_INTEGRITY_UNSAFE_POINTER")
    current = json.loads(pointer.read_bytes())
    name = current["release"]
    if (not isinstance(name, str) or len(name) != 64 or
            any(c not in "0123456789abcdef" for c in name)):
        raise ValueError("SEMANTIC_TEST_INTEGRITY_UNSAFE_RELEASE")
    release = folder / "releases" / name
    if release.is_symlink() or not release.is_dir():
        raise ValueError("SEMANTIC_TEST_INTEGRITY_UNSAFE_RELEASE")
    manifest_path = release / "manifest.json"
    if manifest_path.is_symlink():
        raise ValueError("SEMANTIC_TEST_INTEGRITY_MANIFEST_SYMLINK")
    raw = manifest_path.read_bytes()
    if _hash(raw) != current["manifest_sha256"]:
        raise ValueError("SEMANTIC_TEST_INTEGRITY_MANIFEST_HASH")
    manifest = json.loads(raw)
    if manifest["release_sha256"] != name or manifest["schema"] != SCHEMA:
        raise ValueError("SEMANTIC_TEST_INTEGRITY_MANIFEST_CONTRACT")
    suites = {}
    for family, info in manifest["suites"].items():
        if family not in {f.name for f in FAMILIES} or info["artifact"] != "suites/"+family+".json":
            raise ValueError("SEMANTIC_TEST_INTEGRITY_SUITE_PATH")
        file = release / info["artifact"]
        if file.is_symlink():
            raise ValueError("SEMANTIC_TEST_INTEGRITY_SUITE_SYMLINK")
        content = file.read_bytes()
        if _hash(content) != info["sha256"]:
            raise ValueError("SEMANTIC_TEST_INTEGRITY_SUITE_HASH:"+family)
        value = json.loads(content)
        if value["family"] != family or value["schema"] != SCHEMA:
            raise ValueError("SEMANTIC_TEST_INTEGRITY_SUITE_SCHEMA")
        suites[family] = value
    return manifest, suites


def status(parity: dict, folder: Path, *, selector="all") -> dict:
    scope = IntegerScope.from_environment(parity)
    manifest, suites = _read_release(Path(folder))
    selected = select_families(selector)
    stale = [name for name in selected
             if name not in suites or
             suites[name]["dependency_state"] != _dependency_state(
                 next(f for f in FAMILIES if f.name == name), scope, parity)]
    return {"selector":selector, "integer_max":scope.maximum,
            "selected":list(selected), "stale":stale,
            "release_sha256":manifest["release_sha256"] if manifest else None}


def _validate_case(case: dict, arithmetic, graph, scope, family):
    if family == "boolean.constants":
        if case["expected"] not in (True, False) or case["law"] != "boolean_constant":
            raise ValueError("SEMANTIC_TEST_INTEGRITY_BOOLEAN_GOLD")
        return
    record = case["record"]
    expression = record["expression"]
    arithmetic.verify(expression)
    value = arithmetic.evaluate(expression)
    law = case["law"]
    # The integer cap constrains every operand as well as the answer.
    def assert_integer_atoms(node):
        if node["kind"] == "number":
            if (type(node["value"]) is not int or
                    not 0 <= node["value"] <= scope.maximum):
                raise ValueError("SEMANTIC_TEST_INTEGRITY_INTEGER_INPUT_BOUNDS")
        else:
            for child in node["args"]:
                assert_integer_atoms(child)
    assert_integer_atoms(expression)
    base = (record if law == "typed_direct_number" else
            {"task":record["task"],"expression":expression["args"][0]})
    # Source ownership is stable over seeds and independent of test bounds.
    source_digest = hashlib.sha256(json.dumps(base,sort_keys=True,
                separators=(",", ":")).encode()).hexdigest()
    if case["source_id"] != source_digest:
        raise ValueError("SEMANTIC_TEST_INTEGRITY_SOURCE_IDENTITY_DRIFT")
    if law == "typed_direct_number":
        expect = case["native_output"]
        vocabulary = {v:i for i,v in enumerate(graph["tokens"])}
        if (type(value) is not int or value != case["expected"] or
                not 0 <= value <= scope.maximum or
                expect != {"identity":"school.number."+str(value),
                           "token_id":vocabulary["school.number."+str(value)]}):
            raise ValueError("SEMANTIC_TEST_INTEGRITY_INTEGER_GOLD")
    elif law == "typed_equality_truth":
        if type(value) is not bool or value != case["expected"]:
            raise ValueError("SEMANTIC_TEST_INTEGRITY_TRUTH_GOLD")
    elif law == "equality_symmetric":
        alternative = case["comparison"]["expression"]
        arithmetic.verify(alternative)
        if (expression["name"] != "EQ" or
                alternative["args"] != list(reversed(expression["args"])) or
                type(value) is not bool or
                arithmetic.evaluate(alternative) != value or value != case["expected"]):
            raise ValueError("SEMANTIC_TEST_INTEGRITY_EQUIVALENCE_LAW")
    elif law == "boolean_double_negation":
        if (type(value) is not bool or case["expected"] != value or
                case["negated"] != (not value) or
                case["double_negated"] != value or
                case["neural_codec_admitted"] is not False):
            raise ValueError("SEMANTIC_TEST_INTEGRITY_NEGATION_LAW")
    else:
        raise ValueError("SEMANTIC_TEST_INTEGRITY_UNKNOWN_LAW")


def check_generated(parity: dict, legacy_root: Path, folder: Path, *,
                    selector="generated") -> bool:
    manifest, suites = _read_release(Path(folder))
    if not manifest or not suites:
        raise ValueError("SEMANTIC_TEST_STALE_NO_GENERATED_TESTS")
    if selector != "generated":
        required = select_families(selector)
        if set(required) - set(suites):
            raise ValueError("SEMANTIC_TEST_STALE_MISSING_REQUIRED_FAMILIES")
    else:
        required = tuple(suites)
    state = status(parity, folder, selector=selector if selector != "generated" else "all")
    if any(family in state["stale"] for family in required):
        raise ValueError("SEMANTIC_TEST_STALE_REGENERATE_REQUIRED:" + ",".join(state["stale"]))
    _, arithmetic, _, _, graph, provenance = _source_stack(legacy_root)
    if provenance != parity["source_sha256"]:
        raise ValueError("SEMANTIC_TEST_INTEGRITY_SOURCE_DRIFT")
    scope = IntegerScope.from_environment(parity)
    seen = {}
    for family, suite in suites.items():
        for case in suite["cases"]:
            if case["partition"] not in ("development", "sealed_proposed"):
                raise ValueError("SEMANTIC_TEST_INTEGRITY_NON_EVALUATION_PARTITION")
            partition = ("sealed" if case["partition"] == "sealed_proposed" else
                         case["partition"])
            if (family != "boolean.constants" and
                    _partition(case["source_id"]) != partition):
                raise ValueError("SEMANTIC_TEST_INTEGRITY_SOURCE_PARTITION_DRIFT")
            if (case["source_id"] in seen and seen[case["source_id"]] != partition):
                raise ValueError("SEMANTIC_TEST_INTEGRITY_SOURCE_LEAK")
            seen[case["source_id"]] = partition
            _validate_case(case, arithmetic, graph, scope, family)
    return True


def regenerate(parity: dict, legacy_root: Path, folder: Path, *,
               selector: str, seed: int = 20261015, count: int = 40):
    """Create a whole new release, publish its pointer in one atomic replace."""
    scope = IntegerScope.from_environment(parity)
    selected = set(select_families(selector))
    folder = Path(folder)
    old_manifest, old_suites = _read_release(folder)
    sampled = generate_integer_curriculum(parity, legacy_root, seed=seed,
                                          count=count, maximum=scope.maximum)
    _, arithmetic, _, _, graph, _ = _source_stack(legacy_root)
    suites = dict(old_suites)
    for family in FAMILIES:
        if family.name in selected:
            suites[family.name] = _suite(family, sampled, arithmetic,
                                         graph, scope, parity, seed, count)
    bytes_by_family = {name:_json(value) for name,value in suites.items()}
    manifest = {"schema":SCHEMA, "source_sha256":parity["source_sha256"],
                "graph_sha256":parity["graph_sha256"],
                "integer_max":scope.maximum,
                "suites":{name:{"artifact":"suites/"+name+".json",
                                "sha256":_hash(blob),
                                "dependencies":value["dependencies"],
                                "dependency_state":value["dependency_state"]}
                          for name,(value,blob) in
                          ((n,(suites[n],bytes_by_family[n])) for n in sorted(suites))}}
    manifest["release_sha256"] = _object_hash(manifest)
    release = folder / "releases" / manifest["release_sha256"]
    if (old_manifest is not None and
            old_manifest["release_sha256"] == manifest["release_sha256"]):
        return old_manifest
    (folder / "releases").mkdir(parents=True, exist_ok=True)
    if not release.exists():
        temp = Path(tempfile.mkdtemp(prefix=".staged-", dir=folder / "releases"))
        try:
            (temp / "suites").mkdir()
            for name, blob in bytes_by_family.items():
                (temp / "suites" / (name + ".json")).write_bytes(blob)
            (temp / "manifest.json").write_bytes(_json(manifest))
            temp.rename(release)
        finally:
            if temp.exists():
                shutil.rmtree(temp)
    else:
        actual = (release / "manifest.json").read_bytes()
        if actual != _json(manifest):
            raise ValueError("SEMANTIC_TEST_INTEGRITY_RELEASE_ID_COLLISION")
    pointer = {"release":manifest["release_sha256"],
               "manifest_sha256":_hash(_json(manifest))}
    fd, scratch = tempfile.mkstemp(prefix=".current-", dir=folder)
    try:
        with os.fdopen(fd,"wb") as output:
            output.write(_json(pointer))
            output.flush()
            os.fsync(output.fileno())
        os.replace(scratch, folder / "current.json")
    finally:
        if os.path.exists(scratch):
            os.unlink(scratch)
    return manifest


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    choice=parser.add_mutually_exclusive_group(required=True)
    choice.add_argument("--regenerate-tests", metavar="SELECTOR")
    choice.add_argument("--plan-tests", metavar="SELECTOR")
    choice.add_argument("--check-tests", metavar="SELECTOR")
    parser.add_argument("--seed", type=int, default=20261015)
    parser.add_argument("--count", type=int, default=40)
    parser.add_argument("--output-dir", type=Path, default=ROOT)
    parser.add_argument("--legacy-root", type=Path, default=LEGACY)
    args=parser.parse_args(argv)
    parity=build_plan(args.legacy_root)
    if args.regenerate_tests:
        result=regenerate(parity,args.legacy_root,args.output_dir,
                          selector=args.regenerate_tests,seed=args.seed,count=args.count)
        print(json.dumps({"regenerated":select_families(args.regenerate_tests),
                          "release_sha256":result["release_sha256"],
                          "integer_max":result["integer_max"],
                          "output_dir":str(args.output_dir)},indent=2))
    elif args.plan_tests:
        print(json.dumps(status(parity,args.output_dir,selector=args.plan_tests),indent=2))
    else:
        check_generated(parity,args.legacy_root,args.output_dir,
                        selector=args.check_tests)
        print("SEMANTIC_GENERATED_TESTS_VALID_AND_CURRENT")


if __name__ == "__main__":
    main()
