export function schoolFixtureRows() {
  return BASE_ROWS.map((row) => ({ ...row, prerequisites: [...row.prerequisites], sourceFamilies: [...row.sourceFamilies] }));
}

export function makeLargeSchoolFixture(size = 240) {
  const base = schoolFixtureRows();
  return Array.from({ length: size }, (_, index) => {
    const source = base[index % base.length];
    return {
      ...source,
      id: source.id + ".F" + String(index + 1).padStart(3, "0"),
      prerequisites: source.prerequisites.map((id) => id + ".F" + String(Math.max(1, index)).padStart(3, "0")),
    };
  });
}
